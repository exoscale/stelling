// Command apigen generates the server code of an API with oapi-codegen, and the vocabulary of the fields of its
// requests, so that errors can only name fields the specification defines
//
//	//go:generate go tool apigen -config cfg.yaml api.yaml
//
// The configuration is the one of oapi-codegen, which must set package and output. The vocabulary is written to
// fields.gen.go, next to the server code. See the example package
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"runtime/debug"
	"strings"

	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/util"
	"go.yaml.in/yaml/v3"
)

const oapiCodegenPath = "github.com/oapi-codegen/oapi-codegen/v2"

func main() {
	config := flag.String("config", "", "the oapi-codegen configuration file")
	flag.Parse()
	if *config == "" || flag.NArg() != 1 {
		log.Fatal("usage: apigen -config cfg.yaml api.yaml")
	}
	if err := run(*config, flag.Arg(0)); err != nil {
		log.Fatal(err)
	}
}

type configuration struct {
	codegen.Configuration `yaml:",inline"`
	OutputFile            string `yaml:"output"`
}

func run(configPath, specPath string) error {
	data, err := os.ReadFile(configPath)
	if err != nil {
		return err
	}
	var cfg configuration
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	if err := dec.Decode(&cfg); err != nil {
		return fmt.Errorf("parse %s: %w", configPath, err)
	}
	cfg.Configuration = cfg.UpdateDefaults()
	if err := cfg.Validate(); err != nil {
		return fmt.Errorf("%s: %w", configPath, err)
	}
	if cfg.OutputFile == "" {
		return fmt.Errorf("%s: output is required", configPath)
	}

	server, err := generateServer(specPath, cfg)
	if err != nil {
		return err
	}
	// Generate prunes and filters the specification it is given, so the vocabulary is built from a fresh copy
	spec, err := util.LoadSwagger(specPath)
	if err != nil {
		return err
	}
	fields, err := generateFields(spec, cfg.PackageName, filepath.Base(specPath))
	if err != nil {
		return err
	}

	if err := os.WriteFile(cfg.OutputFile, server, 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(filepath.Dir(cfg.OutputFile), "fields.gen.go"), fields, 0o644)
}

// generateServer generates the code oapi-codegen would, stamped with its version as if it was run directly
func generateServer(specPath string, cfg configuration) ([]byte, error) {
	bi, ok := debug.ReadBuildInfo()
	if !ok {
		return nil, errors.New("read build info")
	}
	for _, dep := range bi.Deps {
		if dep.Path == oapiCodegenPath {
			cfg.NoVCSVersionOverride = &dep.Version
		}
	}

	overlay := util.LoadSwaggerWithOverlayOpts{Path: cfg.OutputOptions.Overlay.Path, Strict: true}
	if cfg.OutputOptions.Overlay.Strict != nil {
		overlay.Strict = *cfg.OutputOptions.Overlay.Strict
	}
	spec, err := util.LoadSwaggerWithOverlay(specPath, overlay)
	if err != nil {
		return nil, err
	}
	code, err := codegen.Generate(spec, cfg.Configuration)
	if err != nil {
		return nil, fmt.Errorf("generate server code: %w", err)
	}
	return []byte(strings.Replace(code, "Code generated by "+bi.Main.Path+" ", "Code generated by "+oapiCodegenPath+" ", 1)), nil
}
