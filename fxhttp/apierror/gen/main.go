// Command gen generates the shared error types and field codes of apierror from problems.json,
// the copy of the table that public-api publishes in its specification as x-problems
//
//	go run ./gen problems.json problems_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"maps"
	"os"
	"slices"
	"strings"
	"text/template"
)

type table struct {
	Types map[string]struct {
		Status int    `json:"status"`
		Title  string `json:"title"`
	} `json:"types"`
	Codes map[string]string `json:"codes"`
}

var tmpl = template.Must(template.New("").Funcs(template.FuncMap{"ident": ident}).Parse(`// Code generated by go run ./gen problems.json problems_gen.go. DO NOT EDIT.

package apierror

// The types shared by every service
var (
{{- range $slug := .TypeSlugs}}{{with index $.Types $slug}}
	{{ident $slug}} = &Type{Slug: {{printf "%q" $slug}}, status: {{.Status}}, Title: {{printf "%q" .Title}}}
{{- end}}{{end}}
)

var sharedTypes = []*Type{ {{- range .TypeSlugs}}{{ident .}}, {{end}} }

// The codes of the field errors
const (
{{- range .CodeNames}}
	Code{{ident .}} Code = {{printf "%q" .}}
{{- end}}
)

var codeMessages = map[Code]string{
{{- range $code := .CodeNames}}
	Code{{ident $code}}: {{printf "%q" (index $.Codes $code)}},
{{- end}}
}
`))

// ident turns a kebab-case slug into a Go identifier, eg invalid-request into InvalidRequest
func ident(slug string) string {
	parts := strings.Split(slug, "-")
	for i, p := range parts {
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: gen <problems.json> <output.go>")
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var t table
	if err := json.Unmarshal(data, &t); err != nil {
		log.Fatalf("parse %s: %v", os.Args[1], err)
	}
	if len(t.Types) == 0 || len(t.Codes) == 0 {
		log.Fatalf("%s must define types and codes", os.Args[1])
	}

	var buf bytes.Buffer
	err = tmpl.Execute(&buf, map[string]any{
		"Types":     t.Types,
		"Codes":     t.Codes,
		"TypeSlugs": slices.Sorted(maps.Keys(t.Types)),
		"CodeNames": slices.Sorted(maps.Keys(t.Codes)),
	})
	if err != nil {
		log.Fatal(err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("format: %v\n%s", err, buf.String())
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Println("wrote", os.Args[2])
}
