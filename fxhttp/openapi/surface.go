package openapi

import (
	"fmt"
	"net/http"
	"strings"
)

// Surface is an API described by a single OpenAPI specification, mounted under a base path
// A service can expose several surfaces, eg a public and an internal API
type Surface struct {
	// Name identifies the surface. The operation id of its specification endpoint is `get-<name>-openapi-spec`
	Name string
	// BasePath is the path under which the surface is mounted, eg "/internal". Empty or "/" mounts it at the root
	// The servers of the spec must declare it, eg `- url: /internal`
	BasePath string
	// Spec describes the surface: requests are validated against it before reaching the handlers
	Spec *Spec
	// ServeSpec serves the self contained specification at <BasePath>/openapi.yaml, at the SpecAliases and on the
	// base path itself. Only enable it for surfaces whose specification may be disclosed to their clients
	ServeSpec bool
	// SpecAliases are additional paths serving the specification, next to <BasePath>/openapi.yaml
	// They require ServeSpec
	SpecAliases []string
	// SpecOptions are applied, after the options of the handler, to render the served specification
	// Use them for options specific to the specification of this surface, such as WithErrorExtension
	SpecOptions []Option
	// Mount returns the handler of the surface, typically built from code generated from the specification
	// The handler must use the error handlers of the MountOptions, and be mounted under its BaseURL
	Mount func(MountOptions) http.Handler
	// Middleware wrap the handler of the surface, after request validation. The first one is the outermost
	Middleware []func(http.Handler) http.Handler
}

// MountOptions are the options a Surface handler must be created with
// They match the options of the strict server generated by oapi-codegen:
//
//	strictHandler := api.NewStrictHandlerWithOptions(server, nil, api.StrictHTTPServerOptions{
//		RequestErrorHandlerFunc:  o.RequestErrorHandler,
//		ResponseErrorHandlerFunc: o.ResponseErrorHandler,
//	})
//	return api.HandlerWithOptions(strictHandler, api.StdHTTPServerOptions{
//		BaseRouter:       http.NewServeMux(),
//		BaseURL:          o.BaseURL,
//		ErrorHandlerFunc: o.RequestErrorHandler,
//	})
type MountOptions struct {
	// BaseURL is the prefix of every route of the surface
	BaseURL string
	// RequestErrorHandler writes the response of requests which can not be decoded or bound
	RequestErrorHandler func(http.ResponseWriter, *http.Request, error)
	// ResponseErrorHandler writes the response of handlers returning an error
	ResponseErrorHandler func(http.ResponseWriter, *http.Request, error)
}

func (s *Surface) basePath() string {
	return strings.TrimSuffix(s.BasePath, "/")
}

// SpecPath returns the path at which the specification of the surface is served
func (s *Surface) specPath() string {
	return s.basePath() + "/openapi.yaml"
}

func (s *Surface) specOperationID() string {
	return fmt.Sprintf("get-%s-openapi-spec", s.Name)
}

func (s *Surface) validate() error {
	if s.Name == "" {
		return fmt.Errorf("surface name is required")
	}
	if s.Spec == nil {
		return fmt.Errorf("surface %q: spec is required", s.Name)
	}
	if s.Mount == nil {
		return fmt.Errorf("surface %q: mount is required", s.Name)
	}
	if s.BasePath != "" && !strings.HasPrefix(s.BasePath, "/") {
		return fmt.Errorf("surface %q: base path must start with a /", s.Name)
	}
	if len(s.SpecAliases) > 0 && !s.ServeSpec {
		return fmt.Errorf("surface %q: spec aliases require ServeSpec", s.Name)
	}
	return s.validateServers()
}

// validateServers checks the servers of the spec declare the base path: the request validator routes the requests
// with them, while the mux routes them with the base path
func (s *Surface) validateServers() error {
	servers := s.Spec.Document().Servers
	if len(servers) == 0 {
		if s.basePath() != "" {
			return fmt.Errorf("surface %q: the spec must declare the base path %q in its servers", s.Name, s.BasePath)
		}
		return nil
	}
	var paths []string
	for _, server := range servers {
		p, err := server.BasePath()
		if err != nil {
			return fmt.Errorf("surface %q: server %q: %w", s.Name, server.URL, err)
		}
		if p = strings.TrimSuffix(p, "/"); p == s.basePath() {
			return nil
		}
		paths = append(paths, p)
	}
	return fmt.Errorf("surface %q: base path %q is not declared by the servers of the spec %q", s.Name, s.BasePath, paths)
}
