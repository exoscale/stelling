package main

import (
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
)

// node is a field of the requests of the API, merged across operations: a vocabulary names what exists somewhere in
// the specification, not what a given operation accepts
type node struct {
	goName string
	props  map[string]*node
	items  *node           // the items of an array
	values *node           // the values of a map
	ins    map[string]bool // where the field is sent: body, path, query, header or cookie
}

func newNode(goName string) *node {
	return &node{goName: goName, props: map[string]*node{}, ins: map[string]bool{}}
}

func (n *node) prop(name string, extensions map[string]any) *node {
	child, ok := n.props[name]
	if !ok {
		child = newNode(codegen.Property{JsonFieldName: name, Extensions: extensions}.GoFieldName())
		n.props[name] = child
	}
	return child
}

func (n *node) leaf() bool {
	return len(n.props) == 0 && n.items == nil && n.values == nil
}

// in returns where the field is sent, when it is a parameter and the vocabulary has a single place for it
func (n *node) in() string {
	if len(n.ins) == 1 && !n.ins["body"] {
		return slices.Collect(maps.Keys(n.ins))[0]
	}
	return ""
}

func collectFields(spec *openapi3.T) *node {
	root := newNode("")
	for _, item := range spec.Paths.Map() {
		for _, op := range item.Operations() {
			for _, p := range slices.Concat(item.Parameters, op.Parameters) {
				if p.Value != nil {
					walk(root.prop(p.Value.Name, p.Value.Extensions), p.Value.Schema, p.Value.In, nil)
				}
			}
			if op.RequestBody != nil && op.RequestBody.Value != nil {
				for _, media := range op.RequestBody.Value.Content {
					walk(root, media.Schema, "body", nil)
				}
			}
		}
	}
	return root
}

// walk adds to n the fields of the value s describes
func walk(n *node, s *openapi3.SchemaRef, in string, visiting []*openapi3.Schema) {
	n.ins[in] = true
	if s == nil || s.Value == nil || slices.Contains(visiting, s.Value) {
		// shortcut: a recursive schema is only named one level deep, name deeper levels if an API needs them
		return
	}
	v := s.Value
	visiting = append(visiting, v)
	for name, p := range v.Properties {
		var extensions map[string]any
		if p.Value != nil {
			extensions = p.Value.Extensions
		}
		walk(n.prop(name, extensions), p, in, visiting)
	}
	if v.Items != nil {
		if n.items == nil {
			n.items = newNode("")
		}
		walk(n.items, v.Items, in, visiting)
	}
	if v.AdditionalProperties.Schema != nil || (v.AdditionalProperties.Has != nil && *v.AdditionalProperties.Has) {
		if n.values == nil {
			n.values = newNode("")
		}
		walk(n.values, v.AdditionalProperties.Schema, in, visiting)
	}
	for _, branch := range slices.Concat(v.OneOf, v.AnyOf) {
		walk(n, branch, in, visiting)
	}
}

// generateFields returns the source of the vocabulary of the fields of the requests of spec
func generateFields(spec *openapi3.T, pkg, source string) ([]byte, error) {
	var body strings.Builder
	if err := writeNode(&body, collectFields(spec), "fields"); err != nil {
		return nil, err
	}
	var imports string
	if strings.Contains(body.String(), "strconv.") {
		imports = "\"strconv\"\n\n"
	}

	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by github.com/exoscale/stelling/fxhttp/openapi/apigen from %s. DO NOT EDIT.

package %s

import (
	%s"github.com/exoscale/stelling/fxhttp/apierror"
)

// Fields names the parameters and the request body fields of the API, to point at them in field errors
var Fields = fields{}.new("")

func fieldsJoin(parent, name string) string {
	if parent == "" {
		return name
	}
	return parent + "." + name
}
`, source, pkg, imports)
	b.WriteString(body.String())
	return format.Source([]byte(b.String()))
}

// writeNode writes the type of n and of its children
// The types of nested fields join the Go names of their path with _, and lower case markers for items and values,
// which no Go name of a field can collide with
func writeNode(b *strings.Builder, n *node, typeName string) error {
	names := slices.Sorted(maps.Keys(n.props))
	goNames := map[string]string{}
	for _, name := range names {
		goName := n.props[name].goName
		if other, ok := goNames[goName]; ok {
			return fmt.Errorf("fields %q and %q of %s are both named %s in Go", other, name, typeName, goName)
		}
		goNames[goName] = name
	}
	for goName, reserved := range map[string]bool{"FieldName": true, "At": n.items != nil, "Key": n.values != nil} {
		if name, ok := goNames[goName]; ok && reserved {
			return fmt.Errorf("field %q of %s is named %s in Go, which the vocabulary uses", name, typeName, goName)
		}
	}

	childType := func(name string) string {
		if n.props[name].leaf() {
			return "apierror.FieldName"
		}
		return typeName + "_" + n.props[name].goName
	}

	fmt.Fprintf(b, "\ntype %s struct {\n", typeName)
	b.WriteString("apierror.FieldName\n")
	for _, name := range names {
		fmt.Fprintf(b, "%s %s\n", n.props[name].goName, childType(name))
	}
	fmt.Fprintf(b, "}\n\nfunc (%s) new(name string) %s {\nreturn %s{\n", typeName, typeName, typeName)
	fmt.Fprintf(b, "FieldName: apierror.NewFieldName(%q, name),\n", n.in())
	for _, name := range names {
		child := n.props[name]
		if child.leaf() {
			fmt.Fprintf(b, "%s: apierror.NewFieldName(%q, fieldsJoin(name, %q)),\n", child.goName, child.in(), name)
		} else {
			fmt.Fprintf(b, "%s: %s{}.new(fieldsJoin(name, %q)),\n", child.goName, childType(name), name)
		}
	}
	b.WriteString("}\n}\n")

	if n.items != nil {
		itemType := typeName + "_at"
		if n.items.leaf() {
			fmt.Fprintf(b, "\n// At names the item i\nfunc (f %s) At(i int) apierror.FieldName {\nreturn apierror.NewFieldName(%q, f.Name()+\"[\"+strconv.Itoa(i)+\"]\")\n}\n", typeName, n.items.in())
		} else {
			fmt.Fprintf(b, "\n// At names the item i\nfunc (f %s) At(i int) %s {\nreturn %s{}.new(f.Name()+\"[\"+strconv.Itoa(i)+\"]\")\n}\n", typeName, itemType, itemType)
			if err := writeNode(b, n.items, itemType); err != nil {
				return err
			}
		}
	}
	if n.values != nil {
		valueType := typeName + "_key"
		if n.values.leaf() {
			fmt.Fprintf(b, "\n// Key names the value of the key k\nfunc (f %s) Key(k string) apierror.FieldName {\nreturn apierror.NewFieldName(%q, fieldsJoin(f.Name(), k))\n}\n", typeName, n.values.in())
		} else {
			fmt.Fprintf(b, "\n// Key names the value of the key k\nfunc (f %s) Key(k string) %s {\nreturn %s{}.new(fieldsJoin(f.Name(), k))\n}\n", typeName, valueType, valueType)
			if err := writeNode(b, n.values, valueType); err != nil {
				return err
			}
		}
	}

	for _, name := range names {
		if !n.props[name].leaf() {
			if err := writeNode(b, n.props[name], childType(name)); err != nil {
				return err
			}
		}
	}
	return nil
}
